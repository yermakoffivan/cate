import { test, expect } from '@playwright/test'
import path from 'node:path'
import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { launchApp, closeApp, expectTerminalText, makeHome, makeProject, seedOnCanvas } from './fixtures/electron-app'

test('agent Review defaults, paginated long diffs and agent-logo filtering', async () => {
  const home = makeHome()
  const project = makeProject(home, { git: true })
  const { electronApp: app, mainWindow: page } = await launchApp({ home, workspace: project })
  try {
    await app.evaluate(({ BrowserWindow }) => { const w = BrowserWindow.getAllWindows()[0]; w.setSize(1700, 1000) })
    const source = await seedOnCanvas(page, 'terminal', { x: 60, y: 100 }, { title: 'Implement login' })
    await expectTerminalText(page, source.panelId, /\S/)
    const fixture = path.resolve(__dirname, 'fixtures/emit-agent-change.cjs')
    const command = `\x15${JSON.stringify(process.execPath)} ${JSON.stringify(fixture)} codex long-session large.ts 2000 500\r`
    await page.evaluate(({ panelId, command }) => window.__cateE2E!.writeTerminal(panelId, command), { panelId: source.panelId, command })
    await expectTerminalText(page, source.panelId, 'CAPTURE_FIXTURE_DONE')
    // A plain new Review must already show recorded changes, with no mode switch.
    const { nodeId, panelId: reviewId } = await seedOnCanvas(page, 'review', { x: 700, y: 100 }, { repoPath: project })
    const node = page.locator(`[data-node-id="${nodeId}"]`)
    await node.locator('.dock-tab-bar').click({ position: { x: 80, y: 12 } })
    await expect(node.locator('[data-review-file="large.ts"]')).toBeVisible({ timeout: 20_000 })
    await expect(node.getByRole('combobox', { name: 'Comparison' })).toHaveCount(0)
    await expect(node.getByRole('button', { name: 'Filter by agent', exact: true })).toHaveAttribute('title', /Codex/)
    await expect(node.getByRole('textbox', { name: 'Filter changed files' })).toHaveCount(0)
    expect((await node.getByRole('toolbar', { name: 'Review actions' }).boundingBox())!.height).toBeLessThan(44)
    const scroll = node.locator('[data-review-scroll]')
    await expect(node.locator('[data-review-diff-scroll]')).toHaveCount(0)
    await expect(node.getByRole('button', { name: 'Next files page', exact: true })).toHaveCount(0)
    // Cold records arrive before Git attribution; wait for their final group
    // before asserting scroll offsets on a mounted diff.
    await expect(node.locator('[data-review-group-title]')).toHaveText('Uncommitted changes')
    await node.getByRole('button', { name: 'Expand large.ts', exact: true }).click()
    await expect(node.locator('[data-new-line="1"]')).toBeAttached()
    await expect(node.locator('[data-new-line="201"]')).toHaveCount(0)
    const diffScroll = node.locator('[data-review-diff-scroll]').first()
    await expect.poll(() => diffScroll.evaluate(el => el.scrollWidth > el.clientWidth)).toBe(true)
    expect(await scroll.evaluate(el => el.scrollWidth - el.clientWidth)).toBeLessThanOrEqual(1)
    const fileHeader = node.locator('[data-review-file="large.ts"] > div').first()
    const headerBefore = (await fileHeader.boundingBox())!
    await diffScroll.evaluate(el => { el.scrollLeft = 160 })
    expect(await diffScroll.evaluate(el => el.scrollLeft)).toBeGreaterThan(100)
    expect((await fileHeader.boundingBox())!.x).toBe(headerBefore.x)
    expect(await scroll.evaluate(el => el.scrollLeft)).toBe(0)
    await diffScroll.evaluate(el => { el.scrollLeft = 0 })
    await scroll.evaluate(el => { el.scrollTop = el.scrollHeight })
    await node.getByRole('button', { name: 'Next diff page', exact: true }).click()
    await expect(node.locator('[data-new-line="201"]')).toBeAttached()
    await expect(node.locator('[data-new-line="1"]')).toHaveCount(0)
    expect(await node.locator('[data-review-file] *').count()).toBeLessThan(3000)
    await scroll.evaluate(el => { el.scrollTop = 0 })
    await page.screenshot({ path: test.info().outputPath('agent-review-page.png') })
    await node.getByRole('button', { name: 'Filter by agent', exact: true }).click()
    await expect(page.getByRole('menu', { name: 'Filter agent changes' })).toBeVisible()
    await expect.poll(async () => {
      const trigger = (await node.getByRole('button', { name: 'Filter by agent', exact: true }).boundingBox())!
      const flyout = (await page.getByRole('menu', { name: 'Filter agent changes' }).boundingBox())!
      return Math.abs(trigger.x + trigger.width / 2 - flyout.x - flyout.width / 2)
    }).toBeLessThan(1)
    await expect(page.getByRole('menuitem', { name: 'Filter by Grok' })).toHaveCount(0)
    await page.getByRole('menuitem', { name: 'Filter by Codex', exact: true }).hover()
    await page.screenshot({ path: test.info().outputPath('agent-review-filter.png') })
    await page.getByRole('menuitem', { name: 'Filter by Codex', exact: true }).click()
    await expect(node.getByRole('button', { name: 'Filter by agent', exact: true })).toHaveAttribute('title', /Codex/)
    await expect(node.locator('[data-review-file="large.ts"]')).toBeVisible()
    // Open sources use spatial selection; only closed sources appear by name.
    await node.getByRole('button', { name: 'Select source panel on canvas', exact: true }).click()
    await expect(page.getByRole('menuitem', { name: 'Implement login', exact: true })).toHaveCount(0)
    await page.getByRole('button', { name: /Use Implement login/ }).click()
    await expect(node.getByRole('button', { name: 'Clear source panel filter', exact: true })).toContainText('Implement login')
    await expect(node.locator('[data-review-file] button[aria-label^="Go to"]')).toHaveCount(0)
    await page.evaluate((id) => window.__cateE2E!.propose({ kind: 'removePanels', ids: [id] }), source.panelId)
    execFileSync('git', ['add', 'large.ts'], { cwd: project })
    execFileSync('git', ['-c', 'user.name=Test', '-c', 'user.email=test@example.test', 'commit', '-qm', 'agent changes'], { cwd: project })
    await page.evaluate((id) => window.__cateE2E!.sessionOp(id, { kind: 'refresh' }), reviewId)
    await expect(node.locator('[data-review-file="large.ts"]')).toBeVisible()
    const head = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: project, encoding: 'utf8' }).trim()
    await expect(node.locator(`[data-review-group="${head}"]`)).toContainText('agent changes')
    await node.getByRole('button', { name: 'Collapse commit agent changes', exact: true }).click()
    await expect(node.locator('[data-review-file="large.ts"]')).toHaveCount(0)
    await node.getByRole('button', { name: 'Expand commit agent changes', exact: true }).click()
    await expect(node.getByRole('button', { name: 'Collapse large.ts', exact: true })).toBeVisible()
    await expect(node.getByRole('button', { name: 'Show active changes' })).toHaveCount(0)
    await node.getByRole('button', { name: 'Source panel history', exact: true }).click()
    const sources = page.getByRole('menu', { name: 'Closed source panels' })
    await expect(sources.getByRole('menuitem', { name: 'Implement login', exact: true })).toContainText('Closed')
    await expect(sources.getByRole('menuitem', { name: 'Implement login', exact: true })).toBeVisible()
    await page.screenshot({ path: test.info().outputPath('closed-source-menu.png') })
    await sources.getByRole('menuitem', { name: 'Implement login', exact: true }).click()
    await expect(node.getByRole('button', { name: 'Show recorded history' })).toHaveCount(0)
    await expect(node.locator('[data-review-file="large.ts"]')).toBeVisible()
    execFileSync('git', ['-c', 'user.name=Test', '-c', 'user.email=test@example.test', 'revert', '--no-edit', head], { cwd: project })
    await page.evaluate((id) => window.__cateE2E!.sessionOp(id, { kind: 'refresh' }), reviewId)
    await expect(node).toContainText('No recorded changes yet')
    const emptyBounds = (await node.locator('[data-review-empty]').boundingBox())!
    const messageBounds = (await node.locator('[data-review-empty-content]').boundingBox())!
    expect(Math.abs(messageBounds.x + messageBounds.width / 2 - emptyBounds.x - emptyBounds.width / 2)).toBeLessThan(2)
    expect(Math.abs(messageBounds.y + messageBounds.height / 2 - emptyBounds.y - emptyBounds.height / 2)).toBeLessThan(2)
  } finally { await closeApp(app, { home }) }
})

test('general Git diffs open in the repository overlay without a Review panel', async () => {
  const home = makeHome()
  const project = makeProject(home, { git: true, files: { 'large.ts': 'before\n' } })
  execFileSync('git', ['add', '.'], { cwd: project })
  execFileSync('git', ['-c', 'user.name=Test', '-c', 'user.email=test@example.test', 'commit', '-qm', 'fixture'], { cwd: project })
  writeFileSync(path.join(project, 'large.ts'), Array.from({ length: 1000 }, (_, index) => `const value${index + 1} = 'after'`).join('\n'))
  const { electronApp: app, mainWindow: page } = await launchApp({ home, workspace: project })
  try {
    await app.evaluate(({ BrowserWindow }) => { BrowserWindow.getAllWindows()[0].setSize(1700, 1000) })
    await page.getByRole('button', { name: 'Repository', exact: true }).click()
    await expect(page.getByRole('textbox', { name: 'Commit message' })).toBeVisible()
    await expect(page.getByRole('button', { name: 'Review changes', exact: true })).toHaveCount(0)
    await expect(page.getByRole('button', { name: 'Expand large.ts', exact: true })).toBeVisible()
    const fileTop = (await page.getByRole('button', { name: 'Expand large.ts', exact: true }).boundingBox())!.y
    await page.getByRole('button', { name: 'Expand large.ts', exact: true }).click()
    expect((await page.getByRole('button', { name: 'Collapse large.ts', exact: true }).boundingBox())!.y).toBe(fileTop)
    const scroll = page.locator('[data-git-diff-scroll]')
    await expect(scroll).toContainText('const value1 =')
    await expect(scroll).not.toContainText('const value201 =')
    await scroll.evaluate(el => { el.scrollTop = el.scrollHeight })
    await expect(scroll).toContainText('const value1000 =')
    await expect(page.getByRole('button', { name: 'Next diff page', exact: true })).toHaveCount(0)
    expect(await page.evaluate(() => window.__cateE2E!.panels().filter(panel => panel.type === 'review').length)).toBe(0)
    await page.getByRole('button', { name: 'Stage large.ts', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Unstage large.ts', exact: true })).toBeVisible()
    await expect(page.getByRole('textbox', { name: 'Commit message' })).toBeVisible()
    await page.getByRole('button', { name: 'Unstage large.ts', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Stage large.ts', exact: true })).toBeVisible()
    await page.screenshot({ path: test.info().outputPath('git-overlay-diff.png') })
    await expect(page.getByRole('textbox', { name: 'Commit message' })).toBeVisible()
    await expect(page.getByRole('button', { name: 'Display', exact: true })).toHaveAttribute('aria-haspopup', 'menu')
    await expect(page.locator('section[aria-label="Repository"] input[type="checkbox"], section[aria-label="Repository"] select')).toHaveCount(0)
    await app.evaluate(({ BrowserWindow }) => { BrowserWindow.getAllWindows()[0].setSize(1000, 850) })
    await expect(page.getByRole('textbox', { name: 'Commit message' })).toBeVisible()
    await expect(scroll).toBeVisible()
    expect(await scroll.evaluate(el => el.clientHeight)).toBeGreaterThan(150)
    await page.screenshot({ path: test.info().outputPath('git-overlay-narrow.png') })
    await page.getByRole('button', { name: 'Collapse all', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Expand large.ts', exact: true })).toBeVisible()
  } finally { await closeApp(app, { home }) }
})
